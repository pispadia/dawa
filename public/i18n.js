let langue = 'fr';
try { langue = localStorage.getItem('dawa.langue') === 'wo' ? 'wo' : 'fr'; } catch {}

export const langueActuelle = () => langue;

export function changerLangue(l) {
  langue = l === 'wo' ? 'wo' : 'fr';
  try { localStorage.setItem('dawa.langue', langue); } catch {}
  document.documentElement.lang = langue;
}

export function t(cle, valeurs = {}) {
  const brut = TEXTES[langue][cle] ?? TEXTES.fr[cle] ?? cle;
  return brut.replace(/\{(\w+)\}/g, (_, k) => valeurs[k] ?? '');
}

// Le SMS d'alerte est toujours en français : il part vers des proches et des soignants.
export function tFr(cle, valeurs = {}) {
  return (TEXTES.fr[cle] ?? cle).replace(/\{(\w+)\}/g, (_, k) => valeurs[k] ?? '');
}
